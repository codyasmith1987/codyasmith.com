// Postbuild: wraps dist/server/entry.mjs to add baseline security
// headers to every response (prerendered HTML, static assets, and
// SSR alike). Astro middleware in src/middleware.ts only fires on
// SSR routes, so without this wrapper the rest of the site (homepage,
// blog, all prerendered pages, /favicon.ico, every static asset)
// ships with zero security headers.
//
// Header values are read from /security-headers.json at build time
// and inlined into the generated wrapper. The same JSON is consumed
// by src/middleware.ts via src/lib/security-headers.ts, so the two
// targets cannot drift. See security-audit-2026-05-12 round 4
// SEC4-003.

import fs from 'node:fs';
import path from 'node:path';

const headersPath = path.resolve('security-headers.json');
const raw = JSON.parse(fs.readFileSync(headersPath, 'utf8'));
const { _comment, ...SECURITY_HEADERS } = raw;

const root = path.resolve('dist/server');
const entry = path.join(root, 'entry.mjs');
const original = path.join(root, 'entry.original.mjs');

if (!fs.existsSync(entry)) {
  console.error('postbuild-security-headers: dist/server/entry.mjs not found, skipping');
  process.exit(0);
}

if (fs.existsSync(original)) {
  console.error('postbuild-security-headers: entry.original.mjs already exists, refusing to double-wrap');
  process.exit(1);
}

fs.renameSync(entry, original);

const headersJson = JSON.stringify(SECURITY_HEADERS, null, 2);

const wrapper = `// Auto-generated by scripts/postbuild-security-headers.mjs.
// Adds baseline security headers to every response (prerendered HTML,
// static assets, and SSR alike). Astro middleware only fires on SSR
// routes, so this wrapper covers everything else. Header values come
// from /security-headers.json at build time.

import http from 'node:http';

const SECURITY_HEADERS = ${headersJson};

const origCreateServer = http.createServer;
http.createServer = function (...args) {
  let optionsArg = null;
  let userHandler = null;

  if (typeof args[0] === 'function') {
    userHandler = args[0];
  } else if (args.length >= 2 && typeof args[1] === 'function') {
    optionsArg = args[0];
    userHandler = args[1];
  }

  if (!userHandler) {
    return origCreateServer.apply(this, args);
  }

  const wrapped = (req, res) => {
    for (const [key, value] of Object.entries(SECURITY_HEADERS)) {
      res.setHeader(key, value);
    }
    userHandler(req, res);
  };

  return optionsArg
    ? origCreateServer.call(this, optionsArg, wrapped)
    : origCreateServer.call(this, wrapped);
};

await import('./entry.original.mjs');
`;

fs.writeFileSync(entry, wrapper);
console.log('postbuild-security-headers: wrapped dist/server/entry.mjs');
