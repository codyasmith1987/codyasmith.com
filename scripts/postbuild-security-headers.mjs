// Postbuild: wraps dist/server/entry.mjs to add baseline security
// headers to every response (prerendered HTML, static assets, and
// SSR alike). Astro middleware in src/middleware.ts only fires on
// SSR routes, so without this wrapper the rest of the site (homepage,
// blog, all prerendered pages, /favicon.ico, every static asset)
// ships with zero security headers.
//
// The wrapper monkey-patches http.createServer so any handler the
// Astro standalone entry passes to it gets pre-decorated with the
// security headers via res.setHeader before Astro runs. Astro's
// SSR middleware can still set its own values; setHeader's last
// write wins for matching keys, which is fine because the values
// match.

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve('dist/server');
const entry = path.join(root, 'entry.mjs');
const original = path.join(root, 'entry.original.mjs');

if (!fs.existsSync(entry)) {
  console.error('postbuild-security-headers: dist/server/entry.mjs not found, skipping');
  process.exit(0);
}

if (fs.existsSync(original)) {
  console.error('postbuild-security-headers: entry.original.mjs already exists, refusing to double-wrap');
  process.exit(1);
}

fs.renameSync(entry, original);

const SECURITY_HEADERS = {
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
  'Content-Security-Policy': "default-src 'self'; script-src 'self' 'unsafe-inline' https://cdn.jsdelivr.net; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' data: blob:; connect-src 'self'; frame-ancestors 'none'; base-uri 'self'; form-action 'self'; object-src 'none'",
  'X-Frame-Options': 'DENY',
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'accelerometer=(), ambient-light-sensor=(), autoplay=(), battery=(), camera=(), cross-origin-isolated=(), display-capture=(), document-domain=(), encrypted-media=(), execution-while-not-rendered=(), execution-while-out-of-viewport=(), fullscreen=(self), geolocation=(), gyroscope=(), keyboard-map=(), magnetometer=(), microphone=(), midi=(), navigation-override=(), payment=(), picture-in-picture=(), publickey-credentials-get=(), screen-wake-lock=(), sync-xhr=(), usb=(), web-share=(), xr-spatial-tracking=(), clipboard-read=(), clipboard-write=(self)',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Resource-Policy': 'same-origin',
};

const headersJson = JSON.stringify(SECURITY_HEADERS, null, 2);

const wrapper = `// Auto-generated by scripts/postbuild-security-headers.mjs.
// Adds baseline security headers to every response (prerendered HTML,
// static assets, and SSR alike). Astro middleware only fires on SSR
// routes, so this wrapper covers everything else.

import http from 'node:http';

const SECURITY_HEADERS = ${headersJson};

const origCreateServer = http.createServer;
http.createServer = function (...args) {
  let optionsArg = null;
  let userHandler = null;

  if (typeof args[0] === 'function') {
    userHandler = args[0];
  } else if (args.length >= 2 && typeof args[1] === 'function') {
    optionsArg = args[0];
    userHandler = args[1];
  }

  if (!userHandler) {
    return origCreateServer.apply(this, args);
  }

  const wrapped = (req, res) => {
    for (const [key, value] of Object.entries(SECURITY_HEADERS)) {
      res.setHeader(key, value);
    }
    userHandler(req, res);
  };

  return optionsArg
    ? origCreateServer.call(this, optionsArg, wrapped)
    : origCreateServer.call(this, wrapped);
};

await import('./entry.original.mjs');
`;

fs.writeFileSync(entry, wrapper);
console.log('postbuild-security-headers: wrapped dist/server/entry.mjs');
